int	ft_atoi(const char *s)
{
	int				i;
	unsigned int	n;
	int				sign;

	n = 0;
	i = 0;
	sign = 1;
	while (((int)s[i] >= 9 && (int)s[i] <= 13) || (s[i] == 32))
		i++;
	if (s[i] == '+' || s[i] == '-')
	{
		if (s[i] == '-')
			sign = -1;
		i++;
	}
	while (s[i] >= '0' && s[i] <= '9')
	{
		n = 10 * n + (s[i] - '0');
		i++;
	}
	return (sign * n);
}
